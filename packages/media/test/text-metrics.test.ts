/**
 * Checks the generated text-metrics table against the real font files, and regenerates it on request:
 *
 *   STUDIO_WRITE_TEXT_METRICS=1 pnpm --filter @studio/media exec vitest run test/text-metrics.test.ts
 *
 * Inter and Inter Display come from assets/fonts; DejaVu Sans and Liberation Sans from the system font
 * directories (Debian/Ubuntu packages fonts-dejavu-core and fonts-liberation). Each family keeps, per
 * character, the WIDEST advance across every weight in ASS font-size units (advance divided by
 * usWinAscent + usWinDescent, which is how libass sizes text), so layout estimates are upper bounds.
 */
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { TEXT_METRICS_CODES, TEXT_METRICS_DATA } from '../src/render/text-metrics-data.js';
import { lineWidthUnits, textMetricsFor } from '../src/render/text-metrics.js';
import { readFontFileMetrics } from './opentype-metrics.js';
import { FONTS_DIR } from './render-fixtures.js';

const OUT = fileURLToPath(new URL('../src/render/text-metrics-data.ts', import.meta.url));
/** Every weight the text styles can select (500–800, plus Regular); Black (900) is never requested. */
const WEIGHTS = ['Regular', 'Medium', 'SemiBold', 'Bold', 'ExtraBold'];

const FAMILY_FILES: Record<string, string[]> = {
  Inter: WEIGHTS.map((w) => `${FONTS_DIR}Inter-${w}.otf`),
  'Inter Display': WEIGHTS.map((w) => `${FONTS_DIR}InterDisplay-${w}.otf`),
  'DejaVu Sans': ['/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'],
  'Liberation Sans': ['/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf', '/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf'],
};

function coveredCharacters(): number[] {
  const codes: number[] = [];
  for (let c = 0x20; c <= 0x7e; c++) codes.push(c);
  for (let c = 0xa0; c <= 0xff; c++) codes.push(c);
  codes.push(0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026);
  return codes;
}

async function measureFamily(files: string[], codes: number[]): Promise<{ emPerSize: number; widths: number[] }> {
  const faces = await Promise.all(files.map((f) => readFontFileMetrics(f)));
  const emPerSize = Math.floor(Math.min(...faces.map((f) => f.unitsPerEm / f.winHeight)) * 1000) / 1000;
  const widths = codes.map((code) => Math.ceil(Math.max(...faces.map((f) => (f.advances.get(code) ?? 0) / f.winHeight)) * 1000));
  return { emPerSize, widths };
}

const available = (files: string[]) => files.every((f) => existsSync(f));

describe.runIf(process.env['STUDIO_WRITE_TEXT_METRICS'] === '1')('text-metrics generator', () => {
  it('writes src/render/text-metrics-data.ts from the font files', async () => {
    const codes = coveredCharacters();
    const lines: string[] = [];
    for (const [family, files] of Object.entries(FAMILY_FILES)) {
      expect(available(files), `font files for ${family}`).toBe(true);
      const m = await measureFamily(files, codes);
      lines.push(`  '${family}': { emPerSize: ${m.emPerSize}, widths: [${m.widths.join(',')}] },`);
    }
    const body = [
      '// Generated by packages/media/test/text-metrics.test.ts (STUDIO_WRITE_TEXT_METRICS=1). Do not edit by hand.',
      '// Widths are thousandths of the ASS font size: the widest advance of each character across all',
      '// weights of the family. emPerSize is units-per-em / (usWinAscent + usWinDescent).',
      '',
      '/** Characters covered by TEXT_METRICS_DATA widths, in order. */',
      `export const TEXT_METRICS_CODES: readonly number[] = [${codes.join(',')}];`,
      '',
      '/** Per-family advance widths (thousandths of the font size) and em-to-size ratio. */',
      'export const TEXT_METRICS_DATA: Readonly<Record<string, { emPerSize: number; widths: readonly number[] }>> = {',
      ...lines,
      '};',
      '',
    ].join('\n');
    await writeFile(OUT, body, 'utf8');
  });
});

describe('text metrics table', () => {
  it('covers the expected characters', () => {
    expect([...TEXT_METRICS_CODES]).toEqual(coveredCharacters());
    for (const family of Object.keys(FAMILY_FILES)) {
      expect(TEXT_METRICS_DATA[family]?.widths).toHaveLength(TEXT_METRICS_CODES.length);
    }
  });

  for (const [family, files] of Object.entries(FAMILY_FILES)) {
    it.runIf(available(files))(`matches the ${family} font files`, async () => {
      const measured = await measureFamily(files, coveredCharacters());
      expect(TEXT_METRICS_DATA[family]).toEqual(measured);
    });
  }

  it('never under-estimates a line and treats unknown characters as wide', () => {
    const inter = textMetricsFor('Inter');
    // "W" is Inter's widest ASCII glyph (~0.875 of the size at ExtraBold); spaces are narrow.
    expect(lineWidthUnits(inter, 'W')).toBeGreaterThanOrEqual(0.875);
    expect(lineWidthUnits(inter, ' ')).toBeLessThan(0.3);
    expect(lineWidthUnits(inter, '💈')).toBeGreaterThanOrEqual(1.2);
    expect(lineWidthUnits(inter, 'ab')).toBeCloseTo(lineWidthUnits(inter, 'a') + lineWidthUnits(inter, 'b'), 6);
    // Unknown families fall back to the widest family in the table.
    expect(lineWidthUnits(textMetricsFor('Comic Sans'), 'W')).toBeGreaterThanOrEqual(lineWidthUnits(textMetricsFor('DejaVu Sans'), 'W'));
  });
});
